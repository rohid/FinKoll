#!/usr/bin/env bash
# setup.sh — Interactive first-time setup for FinKoll.
#
# Creates your .env file: generates the two secrets automatically, asks for a
# username and password, hashes the password for you, and writes everything to
# the right place (root .env for Docker, or backend/.env for Node dev mode).
#
# Usage:  bash scripts/setup.sh
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT"

echo "╔══════════════════════════════════════╗"
echo "║        FinKoll — First-time setup     ║"
echo "╚══════════════════════════════════════╝"
echo

# ── Helpers ───────────────────────────────────────────────────────────────────

# Generate a random hex string of N bytes (→ 2N hex characters).
gen_hex() {
  local n="$1"
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "$n"
  elif command -v node >/dev/null 2>&1; then
    node -e "console.log(require('crypto').randomBytes($n).toString('hex'))"
  else
    LC_ALL=C tr -dc 'a-f0-9' < /dev/urandom | head -c $(( n * 2 )); echo
  fi
}

# Hash a password with bcrypt (cost 12). Prefers local Node + bcryptjs, falls
# back to a throwaway Docker container. Prints the hash to stdout.
hash_pw() {
  local pw="$1"
  if command -v node >/dev/null 2>&1; then
    if [ ! -f "$ROOT/backend/node_modules/bcryptjs/package.json" ]; then
      echo "  · installing bcryptjs to hash your password…" >&2
      ( cd "$ROOT/backend" && npm install bcryptjs --silent >/dev/null 2>&1 ) || true
    fi
    if [ -f "$ROOT/backend/node_modules/bcryptjs/package.json" ]; then
      ( cd "$ROOT/backend" && PW="$pw" node -e 'require("bcryptjs").hash(process.env.PW,12).then(h=>process.stdout.write(h))' )
      return 0
    fi
  fi
  if command -v docker >/dev/null 2>&1; then
    echo "  · hashing your password via Docker…" >&2
    docker run --rm -e PW="$pw" node:20-alpine sh -lc \
      'npm i -s bcryptjs >/dev/null 2>&1 && node -e "require(\"bcryptjs\").hash(process.env.PW,12).then(h=>process.stdout.write(h))"'
    return 0
  fi
  return 1
}

# ── 1. How will you run it? ─────────────────────────────────────────────────────
echo "How will you run FinKoll?"
echo "  1) Docker        (recommended — one command to start)"
echo "  2) Node.js dev   (npm / development mode)"
read -rp "Choose [1]: " mode_choice
case "${mode_choice:-1}" in
  2) MODE=node;  ENV_FILE="$ROOT/backend/.env"; DEFAULT_URL="http://localhost:5173" ;;
  *) MODE=docker; ENV_FILE="$ROOT/.env";         DEFAULT_URL="http://localhost" ;;
esac
echo

# Don't clobber an existing config without asking.
if [ -f "$ENV_FILE" ]; then
  echo "⚠  $ENV_FILE already exists (it may hold secrets for an existing database)."
  read -rp "Overwrite it? [y/N]: " ow
  case "$ow" in [Yy]*) ;; *) echo "Aborted — your existing file was left untouched."; exit 0 ;; esac
  echo
fi

# ── 2. Username ─────────────────────────────────────────────────────────────────
read -rp "Login username [admin]: " USERNAME
USERNAME="${USERNAME:-admin}"

# ── 3. Password (hidden, confirmed) ─────────────────────────────────────────────
while true; do
  read -rsp "Choose a password: " PW; echo
  if [ -z "$PW" ]; then echo "  Password can't be empty."; continue; fi
  if [ "${#PW}" -lt 8 ]; then echo "  Tip: use at least 8 characters."; fi
  read -rsp "Confirm password:  " PW2; echo
  if [ "$PW" != "$PW2" ]; then echo "  Passwords didn't match — try again."; echo; continue; fi
  break
done
echo

# ── 4. Optional: browser URL (for CORS / remote access) ─────────────────────────
echo "URL you'll open in your browser (change only for a Pi / another device)."
read -rp "  [$DEFAULT_URL]: " FRONTEND_URL
FRONTEND_URL="${FRONTEND_URL:-$DEFAULT_URL}"
echo

# ── 5. Generate secrets + hash ──────────────────────────────────────────────────
echo "Generating secrets and hashing your password…"
JWT_SECRET="$(gen_hex 32)"        # 64 hex chars
DB_KEY="$(gen_hex 16)"            # exactly 32 hex chars (required)

if ! HASH="$(hash_pw "$PW")" || [ -z "$HASH" ]; then
  echo "ERROR: couldn't hash the password — you need Node.js or Docker installed." >&2
  exit 1
fi
unset PW PW2

# In the root .env, Docker Compose treats '$' specially — double them so the hash
# survives. (Node dev reads backend/.env literally and needs no escaping.)
STORED_HASH="$HASH"
if [ "$MODE" = docker ]; then
  STORED_HASH="$(printf '%s' "$HASH" | sed 's/\$/\$\$/g')"
fi

# ── 6. Write the file ────────────────────────────────────────────────────────────
umask 077
cat > "$ENV_FILE" <<EOF
# Generated by scripts/setup.sh — keep this file private, never commit it.
JWT_SECRET=$JWT_SECRET
DB_ENCRYPTION_KEY=$DB_KEY
ADMIN_USERNAME=$USERNAME
ADMIN_PASSWORD_HASH=$STORED_HASH
FRONTEND_URL=$FRONTEND_URL
EOF
chmod 600 "$ENV_FILE" 2>/dev/null || true

echo
echo "✓ Wrote $ENV_FILE"
echo "  Username: $USERNAME    (log in with the password you just chose)"
echo "  ⚠ Keep DB_ENCRYPTION_KEY safe — the database can't be opened without it."
echo

# ── 7. Offer to start ────────────────────────────────────────────────────────────
if [ "$MODE" = docker ]; then
  echo "To start:  docker compose up -d --build      then open $FRONTEND_URL"
  read -rp "Start it now with Docker? [y/N]: " go
  case "$go" in [Yy]*) docker compose up -d --build ;; esac
else
  echo "To start:  bash scripts/start.sh             then open $FRONTEND_URL"
  read -rp "Start the dev servers now? [y/N]: " go
  case "$go" in [Yy]*) exec bash "$ROOT/scripts/start.sh" ;; esac
fi

echo "Done. 🎉"
