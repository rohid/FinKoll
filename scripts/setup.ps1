# setup.ps1 — Interactive first-time setup for FinKoll (Windows PowerShell).
#
# Creates your .env file: generates the two secrets automatically, asks for a
# username and password, hashes the password for you, and writes everything to
# the right place (root .env for Docker, or backend\.env for Node dev mode).
#
# Usage:  powershell -ExecutionPolicy Bypass -File scripts\setup.ps1

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

Write-Host "==============================================="
Write-Host "         FinKoll - First-time setup"
Write-Host "==============================================="
Write-Host ""

function Gen-Hex($n) {
  $bytes = New-Object 'System.Byte[]' $n
  (New-Object System.Security.Cryptography.RNGCryptoServiceProvider).GetBytes($bytes)
  -join ($bytes | ForEach-Object { $_.ToString('x2') })
}

function Hash-Pw($pw) {
  if (Get-Command node -ErrorAction SilentlyContinue) {
    if (-not (Test-Path "$Root\backend\node_modules\bcryptjs\package.json")) {
      Write-Host "  - installing bcryptjs to hash your password..."
      Push-Location "$Root\backend"; npm install bcryptjs --silent 2>$null | Out-Null; Pop-Location
    }
    if (Test-Path "$Root\backend\node_modules\bcryptjs\package.json") {
      Push-Location "$Root\backend"
      $env:PW = $pw
      $h = node -e 'require("bcryptjs").hash(process.env.PW,12).then(h=>process.stdout.write(h))'
      Remove-Item Env:\PW
      Pop-Location
      return $h
    }
  }
  if (Get-Command docker -ErrorAction SilentlyContinue) {
    Write-Host "  - hashing your password via Docker..."
    return docker run --rm -e PW="$pw" node:20-alpine sh -lc 'npm i -s bcryptjs >/dev/null 2>&1 && node -e "require(\"bcryptjs\").hash(process.env.PW,12).then(h=>process.stdout.write(h))"'
  }
  throw "Couldn't hash the password - you need Node.js or Docker installed."
}

# 1. Run mode
Write-Host "How will you run FinKoll?"
Write-Host "  1) Docker        (recommended)"
Write-Host "  2) Node.js dev"
$modeChoice = Read-Host "Choose [1]"
if ($modeChoice -eq "2") {
  $Mode = "node"; $EnvFile = "$Root\backend\.env"; $DefaultUrl = "http://localhost:5173"
} else {
  $Mode = "docker"; $EnvFile = "$Root\.env"; $DefaultUrl = "http://localhost"
}
Write-Host ""

if (Test-Path $EnvFile) {
  Write-Host "WARNING: $EnvFile already exists (it may hold secrets for an existing database)."
  $ow = Read-Host "Overwrite it? [y/N]"
  if ($ow -notmatch '^[Yy]') { Write-Host "Aborted - your existing file was left untouched."; exit 0 }
  Write-Host ""
}

# 2. Username
$Username = Read-Host "Login username [admin]"
if ([string]::IsNullOrWhiteSpace($Username)) { $Username = "admin" }

# 3. Password (hidden, confirmed)
while ($true) {
  $sec1 = Read-Host "Choose a password" -AsSecureString
  $pw1 = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec1))
  if ([string]::IsNullOrEmpty($pw1)) { Write-Host "  Password can't be empty."; continue }
  if ($pw1.Length -lt 8) { Write-Host "  Tip: use at least 8 characters." }
  $sec2 = Read-Host "Confirm password" -AsSecureString
  $pw2 = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($sec2))
  if ($pw1 -ne $pw2) { Write-Host "  Passwords didn't match - try again."; Write-Host ""; continue }
  break
}
Write-Host ""

# 4. Browser URL
Write-Host "URL you'll open in your browser (change only for a Pi / another device)."
$FrontendUrl = Read-Host "  [$DefaultUrl]"
if ([string]::IsNullOrWhiteSpace($FrontendUrl)) { $FrontendUrl = $DefaultUrl }
Write-Host ""

# 5. Generate secrets + hash
Write-Host "Generating secrets and hashing your password..."
$JwtSecret = Gen-Hex 32   # 64 hex chars
$DbKey     = Gen-Hex 16   # exactly 32 hex chars (required)
$Hash      = Hash-Pw $pw1
if ([string]::IsNullOrEmpty($Hash)) { throw "Password hashing failed." }

# Docker Compose treats '$' specially in the root .env - double them.
$StoredHash = $Hash
if ($Mode -eq "docker") { $StoredHash = $Hash -replace '\$', '$$$$' }

# 6. Write the file
$lines = @(
  "# Generated by scripts\setup.ps1 - keep this file private, never commit it.",
  "JWT_SECRET=$JwtSecret",
  "DB_ENCRYPTION_KEY=$DbKey",
  "ADMIN_USERNAME=$Username",
  "ADMIN_PASSWORD_HASH=$StoredHash",
  "FRONTEND_URL=$FrontendUrl"
)
Set-Content -Path $EnvFile -Value $lines -Encoding ascii

Write-Host ""
Write-Host "OK - wrote $EnvFile"
Write-Host "  Username: $Username    (log in with the password you just chose)"
Write-Host "  Keep DB_ENCRYPTION_KEY safe - the database can't be opened without it."
Write-Host ""

# 7. Offer to start
if ($Mode -eq "docker") {
  Write-Host "To start:  docker compose up -d --build      then open $FrontendUrl"
  $go = Read-Host "Start it now with Docker? [y/N]"
  if ($go -match '^[Yy]') { docker compose up -d --build }
} else {
  Write-Host "To start (two terminals):"
  Write-Host "  npm run dev --prefix backend"
  Write-Host "  npm run dev --prefix frontend"
  Write-Host "then open $FrontendUrl"
}

Write-Host "Done."
